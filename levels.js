// Helper for game.js — найти уровень по id.
window.LEVELS.byId = function (id) {
  for (let i = 0; i < window.LEVELS.length; i++) {
    if (window.LEVELS[i].id === id) return window.LEVELS[i];
  }
  return null;
};
